import { zipSync, strToU8 } from 'fflate'
import type { VaultSecret } from './vaultTypes'

export const VAULT_MAX_FILE_BYTES = 2 * 1024 * 1024

export const SECRET_FILE_ACCEPT =
  '.txt,.md,.markdown,.json,.pem,.key,.pub,.p8,.crt,.cer,.env,.yaml,.yml,.toml,.ini,.conf,.cfg,.xml,.csv,.asc,.gpg,.jks,.p12,.pfx,.keystore'

export function detectSecretFileExt(name: string, meta?: Record<string, any>): string {
  const fromMeta = typeof meta?.file_ext === 'string' ? meta.file_ext.trim().toLowerCase() : ''
  if (fromMeta) return fromMeta
  const lower = name.trim().toLowerCase()
  if (lower === '.env' || lower.startsWith('.env.')) return 'env'
  if (['id_rsa', 'id_ed25519', 'id_ecdsa', 'id_dsa'].includes(lower)) return 'key'
  const idx = lower.lastIndexOf('.')
  if (idx > 0 && idx < lower.length - 1) return lower.slice(idx + 1)
  return 'txt'
}

export function formatSecretFileSize(bytes?: number): string {
  if (!bytes || bytes <= 0) return '0 B'
  if (bytes < 1024) return `${bytes} B`
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(1)} KB`
  return `${(bytes / (1024 * 1024)).toFixed(2)} MB`
}

export function mimeForSecretExt(ext: string, isBinary = false): string {
  if (isBinary) return 'application/octet-stream'
  switch (ext) {
    case 'json':
      return 'application/json;charset=utf-8'
    case 'md':
    case 'markdown':
      return 'text/markdown;charset=utf-8'
    case 'pem':
    case 'key':
    case 'crt':
    case 'p8':
      return 'application/x-pem-file;charset=utf-8'
    case 'yaml':
    case 'yml':
      return 'application/yaml;charset=utf-8'
    case 'xml':
      return 'application/xml;charset=utf-8'
    case 'csv':
      return 'text/csv;charset=utf-8'
    default:
      return 'text/plain;charset=utf-8'
  }
}

export async function readSecretUploadFile(file: File): Promise<{
  content: string
  encoding: 'utf8' | 'base64'
  ext: string
  sizeBytes: number
}> {
  if (file.size > VAULT_MAX_FILE_BYTES) {
    throw new Error(`File "${file.name}" exceeds the 2 MiB Vault limit.`)
  }
  const buffer = await file.arrayBuffer()
  const bytes = new Uint8Array(buffer)
  const ext = detectSecretFileExt(file.name)
  const forceBinary = ['jks', 'p12', 'pfx', 'keystore', 'bin', 'gpg'].includes(ext) &&
    bytes.some((b) => b === 0)
  const hasNullByte = bytes.some((b) => b === 0)

  if (!forceBinary && !hasNullByte) {
    try {
      const decoded = new TextDecoder('utf-8', { fatal: true }).decode(bytes)
      return { content: decoded, encoding: 'utf8', ext, sizeBytes: bytes.length }
    } catch {
      // Fallback to base64 below if non-UTF8 bytes
    }
  }

  let binary = ''
  for (let i = 0; i < bytes.length; i++) {
    binary += String.fromCharCode(bytes[i])
  }
  return { content: btoa(binary), encoding: 'base64', ext, sizeBytes: bytes.length }
}

export function downloadBlob(blob: Blob, filename: string) {
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = filename
  document.body.appendChild(a)
  a.click()
  document.body.removeChild(a)
  URL.revokeObjectURL(url)
}

export function generateKeyStoreCredentialsText(s: VaultSecret): string {
  const meta = s.metadata || {}
  const alias = meta.key_alias || '-'
  const pass = meta.store_password || '-'
  const keyPass = meta.key_password || pass

  return `# KeyStore Credentials & Configuration
# Generated by GravSpace Vault
# Date: ${new Date().toISOString()}

KEYSTORE_NAME=${s.name}
ENVIRONMENT=${s.environment}
CURRENT_VERSION=v${s.current_version}

# KeyStore Access Credentials
KEY_ALIAS=${alias}
STORE_PASSWORD=${pass}
KEY_PASSWORD=${keyPass}

# Example Gradle configuration (android/app/build.gradle):
# signingConfigs {
#     release {
#         storeFile file("${s.name}")
#         storePassword "${pass}"
#         keyAlias "${alias}"
#         keyPassword "${keyPass}"
#     }
# }
`
}

export function downloadSecretFile(s: VaultSecret, plaintext: string) {
  if (s.secret_type === 'file') {
    const filename = (typeof s.metadata?.file_name === 'string' && s.metadata.file_name) || s.name
    const ext = detectSecretFileExt(filename, s.metadata)
    const encoding = s.metadata?.encoding === 'base64' ? 'base64' : 'utf8'

    if (encoding === 'utf8') {
      const blob = new Blob([plaintext], { type: mimeForSecretExt(ext, false) })
      downloadBlob(blob, filename)
      return
    }
  }

  if (s.secret_type === 'keystore' || s.secret_type === 'file') {
    const filename = (typeof s.metadata?.file_name === 'string' && s.metadata.file_name) || s.name
    let b64 = plaintext.trim()
    if (b64.startsWith('data:')) {
      const idx = b64.indexOf(',')
      if (idx !== -1) b64 = b64.slice(idx + 1)
    }
    try {
      const byteCharacters = atob(b64)
      const byteNumbers = new Array(byteCharacters.length)
      for (let i = 0; i < byteCharacters.length; i++) {
        byteNumbers[i] = byteCharacters.charCodeAt(i)
      }
      const byteArray = new Uint8Array(byteNumbers)
      const blob = new Blob([byteArray], { type: 'application/octet-stream' })
      downloadBlob(blob, filename)
    } catch {
      const blob = new Blob([plaintext], { type: 'text/plain;charset=utf-8' })
      downloadBlob(blob, filename)
    }
  } else if (s.secret_type === 'certificate') {
    try {
      const parsed = JSON.parse(plaintext)
      const content = `${parsed.certificate || ''}\n${parsed.private_key || ''}`
      const blob = new Blob([content], { type: 'application/x-pem-file' })
      const ext = s.name.endsWith('.pem') || s.name.endsWith('.crt') ? '' : '.pem'
      downloadBlob(blob, `${s.name}${ext}`)
    } catch {
      const blob = new Blob([plaintext], { type: 'application/x-pem-file' })
      downloadBlob(blob, s.name)
    }
  } else {
    const blob = new Blob([plaintext], { type: 'text/plain;charset=utf-8' })
    const ext = s.name.endsWith('.env') || s.name.endsWith('.txt') ? '' : '.txt'
    downloadBlob(blob, `${s.name}${ext}`)
  }
}

export function downloadKeyStoreCredentials(s: VaultSecret) {
  const content = generateKeyStoreCredentialsText(s)
  const blob = new Blob([content], { type: 'text/plain;charset=utf-8' })
  const baseName = s.name.replace(/\.[^/.]+$/, '')
  downloadBlob(blob, `${baseName}-credentials.txt`)
}

export function downloadKeyStoreBundle(s: VaultSecret, plaintext: string) {
  const baseName = s.name.replace(/\.[^/.]+$/, '')
  const credsText = generateKeyStoreCredentialsText(s)

  let keystoreBytes: Uint8Array
  let b64 = plaintext.trim()
  if (b64.startsWith('data:')) {
    const idx = b64.indexOf(',')
    if (idx !== -1) b64 = b64.slice(idx + 1)
  }
  try {
    const byteCharacters = atob(b64)
    keystoreBytes = new Uint8Array(byteCharacters.length)
    for (let i = 0; i < byteCharacters.length; i++) {
      keystoreBytes[i] = byteCharacters.charCodeAt(i)
    }
  } catch {
    keystoreBytes = new TextEncoder().encode(plaintext)
  }

  const readme = `KeyStore Bundle: ${s.name}
Generated by GravSpace Secrets & Agent Vault
Date: ${new Date().toISOString()}

Contents:
1. ${s.name} - The binary Android/Java KeyStore.
2. ${baseName}-credentials.txt - Key Alias and Passwords.

Usage with Android Gradle:
Copy ${s.name} to your android/app directory, and set storePassword & keyPassword according to ${baseName}-credentials.txt.
`

  const zipped = zipSync({
    [s.name]: keystoreBytes,
    [`${baseName}-credentials.txt`]: strToU8(credsText),
    'README.txt': strToU8(readme),
  })

  const zipBlob = new Blob([zipped.buffer as ArrayBuffer], { type: 'application/zip' })
  downloadBlob(zipBlob, `${baseName}-bundle.zip`)
}
